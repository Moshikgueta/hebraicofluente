import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { createHmac } from 'node:crypto';
const B='http://127.0.0.1:8787'; const MAIL=readFileSync('/tmp/claude-0/ui-mail','utf8').trim();
const ok=(c,m)=>console.log(`${c?'✓':'✗'} ${m}`);
const br=await chromium.launch({executablePath:'/opt/pw-browsers/chromium'}); const p=await (await br.newContext()).newPage();
await p.request.post(`${B}/api/auth/login`,{data:{email:MAIL,password:'senha-boa-123'}});
await p.goto(`${B}/perfil/`,{waitUntil:'load'}); await p.waitForTimeout(2500);
const cx=p.getByRole('checkbox',{name:/Quero receber um e-mail quando o/});
ok(await cx.count()===1, `caixa no perfil: "${(await p.locator('label:has(input[type=checkbox])').textContent())?.trim()}"`);
ok(!(await cx.isChecked()), 'começa desmarcada');
await cx.check(); await p.waitForTimeout(800);
let me=await p.evaluate(()=>fetch('/api/me').then(r=>r.json())); ok(me.account.novidades===true, 'marcar grava no servidor');
await p.reload({waitUntil:'load'}); await p.waitForTimeout(2000);
ok(await p.getByRole('checkbox',{name:/Quero receber/}).isChecked(), 'continua marcada depois de recarregar');
const segredo=(readFileSync('../.dev.vars','utf8').match(/^SESSION_SECRET\s*=\s*"?([^"\n]+)"?/m)||[])[1];
const id=me.account.id; const t=`${id}.${createHmac('sha256',segredo).update(`novidades:${id}`).digest('base64url')}`;
const v=await (await br.newContext()).newPage();
await v.goto(`${B}/sair-da-lista/?t=${encodeURIComponent(t)}`,{waitUntil:'load'}); await v.waitForTimeout(1500);
me=await p.evaluate(()=>fetch('/api/me').then(r=>r.json())); ok(me.account.novidades===true, 'abrir o link NÃO tira da lista');
await v.getByRole('button',{name:'Sair da lista'}).click(); await v.waitForTimeout(1200);
ok((await v.textContent('main'))?.includes('não vai mais receber'), 'o botão confirma a saída');
me=await p.evaluate(()=>fetch('/api/me').then(r=>r.json())); ok(me.account.novidades===false, 'e o servidor tirou da lista');
await v.goto(`${B}/sair-da-lista/?t=${id}.forjadoforjadoforjadoforjado`,{waitUntil:'load'}); await v.waitForTimeout(1200);
await v.getByRole('button',{name:'Sair da lista'}).click(); await v.waitForTimeout(1000);
ok((await v.textContent('main'))?.includes('não está completo'), 'link adulterado é recusado');
const html=await p.evaluate(()=>fetch('/sair-da-lista/').then(r=>r.text())); ok(/noindex/.test(html), 'página com noindex');
await br.close();
