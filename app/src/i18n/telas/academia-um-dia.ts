/** O nome e a frase de uma parada, pelo id (lib/engine/um-dia.ts). */
export const textoDaParada = (id: string) => {
  const K = id[0]!.toUpperCase() + id.slice(1);
  const t = tx as unknown as Record<string, string>;
  return { nome: t[`nome${K}`] ?? id, desc: t[`desc${K}`] ?? '' };
};
